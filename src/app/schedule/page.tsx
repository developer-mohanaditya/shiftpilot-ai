"use client";

import { useState } from "react";
import {
  Sparkles,
  Brain,
  CheckCircle2,
  RotateCcw,
  AlertCircle,
  Pencil,
  Plus,
  X,
  UserCheck,
  AlertTriangle,
  UserX,
} from "lucide-react";

import { PageHeader } from "@/components/layout/page-header";
import { RoleBadge } from "@/components/role-badge";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { DAY_LABELS, ROLE_LABELS } from "@/domain/labels";
import {
  DAYS_OF_WEEK,
  SHIFT_PERIOD_IDS,
  type DayOfWeek,
  type Role,
  type ShiftPeriodId,
} from "@/domain/types";
import { formatClock, formatCurrency } from "@/lib/format";
import { useAppStore } from "@/store/app-store";
import { evaluateSchedule } from "@/algorithms/metrics";

interface EditingSlot {
  day: DayOfWeek;
  periodId: ShiftPeriodId;
  role: Role;
  assignmentIndex: number; // index in schedule.assignments, or -1 if new
  currentEmployeeId: string | null;
}

export default function SchedulePage() {
  const { data, generateSchedule, applyPredictedDemand, resetData, updateAssignments } =
    useAppStore();
  const [isGenerating, setIsGenerating] = useState(false);
  const [selectedAlgo, setSelectedAlgo] = useState<"genetic" | "baseline">("genetic");
  const [editingSlot, setEditingSlot] = useState<EditingSlot | null>(null);

  const { restaurant, requirements, employees, schedule } = data;

  const metrics = schedule
    ? evaluateSchedule(restaurant, employees, requirements, schedule.assignments)
    : null;

  function handleGenerate() {
    setIsGenerating(true);
    setTimeout(() => {
      generateSchedule(selectedAlgo);
      setIsGenerating(false);
    }, 50);
  }

  function handleSaveAssignment(newEmployeeId: string | null) {
    if (!editingSlot || !schedule) return;

    const currentAssignments = [...schedule.assignments];

    if (newEmployeeId === null) {
      // Remove assignment if existing
      if (editingSlot.assignmentIndex >= 0) {
        currentAssignments.splice(editingSlot.assignmentIndex, 1);
      }
    } else {
      if (editingSlot.assignmentIndex >= 0) {
        // Update existing assignment
        const existing = currentAssignments[editingSlot.assignmentIndex];
        if (existing) {
          currentAssignments[editingSlot.assignmentIndex] = {
            ...existing,
            employeeId: newEmployeeId,
          };
        }
      } else {
        // Add new assignment to fill vacancy
        currentAssignments.push({
          day: editingSlot.day,
          periodId: editingSlot.periodId,
          role: editingSlot.role,
          employeeId: newEmployeeId,
        });
      }
    }

    updateAssignments(currentAssignments);
    setEditingSlot(null);
  }

  return (
    <>
      <PageHeader
        title="Schedule"
        description="Staffing requirements derived from predictive covers, with automated roster assignments generated by optimization algorithms or fine-tuned manually."
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              onClick={() => applyPredictedDemand()}
              title="Predict weekly guest covers and recalculate staffing needs"
            >
              <Brain className="h-4 w-4 mr-1 text-primary" />
              Forecast Demand (ML)
            </Button>
            <div className="flex rounded-md border border-input bg-background p-0.5 text-xs">
              <button
                type="button"
                className={`rounded px-2.5 py-1 font-medium transition-colors ${
                  selectedAlgo === "genetic"
                    ? "bg-primary text-primary-foreground"
                    : "text-muted-foreground hover:text-foreground"
                }`}
                onClick={() => setSelectedAlgo("genetic")}
              >
                Genetic AI
              </button>
              <button
                type="button"
                className={`rounded px-2.5 py-1 font-medium transition-colors ${
                  selectedAlgo === "baseline"
                    ? "bg-primary text-primary-foreground"
                    : "text-muted-foreground hover:text-foreground"
                }`}
                onClick={() => setSelectedAlgo("baseline")}
              >
                Baseline
              </button>
            </div>
            <Button size="sm" onClick={handleGenerate} disabled={isGenerating}>
              <Sparkles className="h-4 w-4 mr-1" />
              {isGenerating ? "Optimizing..." : "Generate schedule"}
            </Button>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => resetData()}
              title="Reset data to defaults"
            >
              <RotateCcw className="h-4 w-4" />
            </Button>
          </div>
        }
      />

      {metrics && (
        <div className="mb-6 grid grid-cols-2 gap-3 sm:grid-cols-4">
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Weekly Payroll</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {formatCurrency(metrics.totalLaborCost, restaurant.currency)}
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Coverage Rate</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {(metrics.coverageRate * 100).toFixed(1)}%
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Total Staff Hours</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {metrics.totalHours} hrs
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Rule Breaches</span>
            <div className="flex items-center gap-1.5 mt-0.5">
              {metrics.violations.unqualified +
                metrics.violations.unavailable +
                metrics.violations.doubleBooked +
                metrics.violations.hoursOverMax ===
              0 ? (
                <>
                  <CheckCircle2 className="h-4 w-4 text-emerald-500" />
                  <span className="text-sm font-medium text-emerald-600">0 violations</span>
                </>
              ) : (
                <>
                  <AlertCircle className="h-4 w-4 text-amber-500" />
                  <span className="text-sm font-medium text-amber-600">
                    {metrics.violations.unqualified +
                      metrics.violations.unavailable +
                      metrics.violations.doubleBooked +
                      metrics.violations.hoursOverMax}{" "}
                    breaches
                  </span>
                </>
              )}
            </div>
          </Card>
        </div>
      )}

      {/* Roster source indicator */}
      {schedule && (
        <div className="mb-3 flex items-center justify-between text-xs text-muted-foreground">
          <div className="flex items-center gap-2">
            <span>Roster mode:</span>
            <Badge variant="outline" className="font-mono text-xs">
              {schedule.source === "genetic"
                ? "Genetic AI Optimizer"
                : schedule.source === "baseline"
                ? "Greedy Heuristic"
                : "Manual Adjustments"}
            </Badge>
          </div>
          <span className="hidden sm:inline text-[11px]">
            Click any employee slot to reassign or fine-tune manually.
          </span>
        </div>
      )}

      <Card className="py-0">
        <div className="overflow-x-auto">
          <table className="w-full min-w-[880px] table-fixed text-sm">
            <thead className="border-b bg-muted/50 text-muted-foreground">
              <tr>
                <th scope="col" className="w-28 px-4 py-3 text-left font-medium">
                  <span className="sr-only">Service</span>
                </th>
                {DAYS_OF_WEEK.map((day) => (
                  <th key={day} scope="col" className="px-2 py-3 text-left font-medium">
                    {DAY_LABELS[day].short}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y">
              {SHIFT_PERIOD_IDS.map((periodId) => {
                const period = restaurant.shiftPeriods[periodId];
                return (
                  <tr key={periodId} className="align-top">
                    <th scope="row" className="px-4 py-4 text-left">
                      <span className="block font-medium">{period.label}</span>
                      <span className="text-xs font-normal text-muted-foreground tabular-nums">
                        {formatClock(period.startMinute)} - {formatClock(period.endMinute)}
                      </span>
                    </th>
                    {DAYS_OF_WEEK.map((day) => {
                      const reqs = requirements.filter(
                        (r) => r.day === day && r.periodId === periodId,
                      );
                      const totalNeeded = reqs.reduce((sum, r) => sum + r.count, 0);

                      // Grab assignments for this shift with their index in schedule.assignments
                      const shiftAssignmentsWithIndex = schedule
                        ? schedule.assignments
                            .map((a, idx) => ({ assignment: a, index: idx }))
                            .filter(
                              (item) =>
                                item.assignment.day === day && item.assignment.periodId === periodId,
                            )
                        : [];

                      return (
                        <td key={day} className="px-2 py-4">
                          {reqs.length === 0 ? (
                            <span className="text-xs text-muted-foreground">Closed</span>
                          ) : (
                            <div className="flex flex-col gap-1.5">
                              <div className="flex items-center justify-between text-xs text-muted-foreground">
                                <span className="tabular-nums font-medium">
                                  {schedule
                                    ? `${shiftAssignmentsWithIndex.length}/${totalNeeded} filled`
                                    : `${totalNeeded} needed`}
                                </span>
                              </div>

                              {/* Assignments view if schedule generated */}
                              {schedule ? (
                                <div className="flex flex-col gap-1">
                                  {shiftAssignmentsWithIndex.map(({ assignment, index }) => {
                                    const emp = employees.find(
                                      (e) => e.id === assignment.employeeId,
                                    );
                                    return (
                                      <button
                                        key={index}
                                        type="button"
                                        onClick={() =>
                                          setEditingSlot({
                                            day,
                                            periodId,
                                            role: assignment.role,
                                            assignmentIndex: index,
                                            currentEmployeeId: assignment.employeeId,
                                          })
                                        }
                                        className="group flex items-center justify-between rounded bg-muted/60 hover:bg-muted p-1 text-xs border border-transparent hover:border-primary/40 transition-colors text-left w-full cursor-pointer"
                                        title="Click to edit or reassign"
                                      >
                                        <div className="flex items-center gap-1 truncate mr-1">
                                          <Pencil className="h-2.5 w-2.5 text-muted-foreground opacity-0 group-hover:opacity-100 transition-opacity" />
                                          <span className="truncate font-medium text-foreground">
                                            {emp
                                              ? `${emp.firstName} ${emp.lastName[0]}.`
                                              : assignment.employeeId}
                                          </span>
                                        </div>
                                        <Badge
                                          variant="outline"
                                          className="text-[10px] px-1 py-0 h-4 border-muted-foreground/30 shrink-0"
                                        >
                                          {ROLE_LABELS[assignment.role as Role]}
                                        </Badge>
                                      </button>
                                    );
                                  })}

                                  {/* Vacant slot button if shift is understaffed */}
                                  {shiftAssignmentsWithIndex.length < totalNeeded && (
                                    <button
                                      type="button"
                                      onClick={() => {
                                        // Pick first requirement role that has fewer assignments than needed
                                        const roleToFill =
                                          reqs.find((r) => {
                                            const filledRoleCount =
                                              shiftAssignmentsWithIndex.filter(
                                                (item) => item.assignment.role === r.role,
                                              ).length;
                                            return filledRoleCount < r.count;
                                          })?.role ?? reqs[0]?.role ?? "server";

                                        setEditingSlot({
                                          day,
                                          periodId,
                                          role: roleToFill,
                                          assignmentIndex: -1,
                                          currentEmployeeId: null,
                                        });
                                      }}
                                      className="flex items-center justify-center gap-1 rounded border border-dashed border-amber-300 dark:border-amber-700 bg-amber-50/50 dark:bg-amber-950/20 px-1.5 py-1 text-[11px] text-amber-700 dark:text-amber-400 hover:bg-amber-100/50 transition-colors cursor-pointer"
                                    >
                                      <Plus className="h-3 w-3" />
                                      <span>Fill vacancy</span>
                                    </button>
                                  )}
                                </div>
                              ) : (
                                /* Role requirements summary badge when no schedule is active */
                                reqs.map((r) => (
                                  <RoleBadge key={r.role} role={r.role} count={r.count} />
                                ))
                              )}
                            </div>
                          )}
                        </td>
                      );
                    })}
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </Card>

      {/* Manual Slot Assignment Modal (Prompt 4) */}
      {editingSlot && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-xs p-4"
          onClick={() => setEditingSlot(null)}
        >
          <div
            className="w-full max-w-lg rounded-xl border bg-background p-6 shadow-xl space-y-4 max-h-[90vh] flex flex-col"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex items-center justify-between pb-2 border-b">
              <div>
                <h3 className="text-base font-semibold text-foreground">
                  {editingSlot.assignmentIndex >= 0 ? "Edit Assignment" : "Fill Vacant Slot"}
                </h3>
                <p className="text-xs text-muted-foreground mt-0.5">
                  {DAY_LABELS[editingSlot.day].long} ({restaurant.shiftPeriods[editingSlot.periodId].label}) - Role:{" "}
                  <span className="font-semibold text-foreground">
                    {ROLE_LABELS[editingSlot.role]}
                  </span>
                </p>
              </div>
              <button
                type="button"
                onClick={() => setEditingSlot(null)}
                className="text-muted-foreground hover:text-foreground rounded p-1"
              >
                <X className="h-4 w-4" />
              </button>
            </div>

            <div className="flex-1 overflow-y-auto space-y-2 pr-1">
              <p className="text-xs font-medium text-muted-foreground">Select employee:</p>
              <div className="space-y-1.5">
                {employees.map((emp) => {
                  const isCurrent = emp.id === editingSlot.currentEmployeeId;
                  const isQualified = emp.roles.includes(editingSlot.role);
                  const isAvailable = (emp.availability[editingSlot.day] ?? []).includes(
                    editingSlot.periodId,
                  );
                  const currentHours = metrics?.hoursByEmployee[emp.id] ?? 0;
                  const hoursWillExceed = currentHours + 4 > emp.maxHoursPerWeek;

                  return (
                    <div
                      key={emp.id}
                      className={`flex items-center justify-between p-2.5 rounded-lg border text-xs transition-colors ${
                        isCurrent
                          ? "border-primary bg-primary/5"
                          : "border-border hover:bg-muted/50"
                      }`}
                    >
                      <div className="space-y-1">
                        <div className="flex items-center gap-2">
                          <span className="font-semibold text-foreground">
                            {emp.firstName} {emp.lastName}
                          </span>
                          <span className="text-muted-foreground font-mono">
                            {formatCurrency(emp.hourlyRate, restaurant.currency, 2)}/hr
                          </span>
                        </div>
                        <div className="flex flex-wrap items-center gap-1.5 text-[11px]">
                          {isQualified ? (
                            <span className="inline-flex items-center gap-0.5 text-emerald-600 dark:text-emerald-400">
                              <UserCheck className="h-3 w-3" /> Qualified
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-0.5 text-amber-600 dark:text-amber-400">
                              <AlertTriangle className="h-3 w-3" /> Not qualified
                            </span>
                          )}

                          <span className="text-muted-foreground">•</span>

                          {isAvailable ? (
                            <span className="text-emerald-600 dark:text-emerald-400">Available</span>
                          ) : (
                            <span className="text-amber-600 dark:text-amber-400">Unavailable</span>
                          )}

                          <span className="text-muted-foreground">•</span>

                          <span
                            className={
                              hoursWillExceed
                                ? "text-amber-600 dark:text-amber-400 font-medium"
                                : "text-muted-foreground"
                            }
                          >
                            {currentHours}/{emp.maxHoursPerWeek} hrs
                          </span>
                        </div>
                      </div>

                      <Button
                        size="sm"
                        variant={isCurrent ? "secondary" : "outline"}
                        className="h-7 text-xs ml-2"
                        onClick={() => handleSaveAssignment(emp.id)}
                      >
                        {isCurrent ? "Selected" : "Assign"}
                      </Button>
                    </div>
                  );
                })}
              </div>
            </div>

            <div className="pt-3 border-t flex items-center justify-between">
              {editingSlot.assignmentIndex >= 0 ? (
                <Button
                  variant="outline"
                  size="sm"
                  className="text-xs text-rose-600 hover:text-rose-700 hover:bg-rose-50 dark:hover:bg-rose-950/20"
                  onClick={() => handleSaveAssignment(null)}
                >
                  <UserX className="h-3.5 w-3.5 mr-1" />
                  Leave Unassigned
                </Button>
              ) : (
                <div />
              )}
              <Button
                variant="ghost"
                size="sm"
                className="text-xs"
                onClick={() => setEditingSlot(null)}
              >
                Close
              </Button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
