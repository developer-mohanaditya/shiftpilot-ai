"use client";

import { useState } from "react";
import { Sparkles, Brain, CheckCircle2, RotateCcw, AlertCircle } from "lucide-react";

import { PageHeader } from "@/components/layout/page-header";
import { RoleBadge } from "@/components/role-badge";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { DAY_LABELS, ROLE_LABELS } from "@/domain/labels";
import { DAYS_OF_WEEK, SHIFT_PERIOD_IDS, type Role } from "@/domain/types";
import { formatClock, formatCurrency } from "@/lib/format";
import { useAppStore } from "@/store/app-store";
import { evaluateSchedule } from "@/algorithms/metrics";

export default function SchedulePage() {
  const { data, generateSchedule, applyPredictedDemand, resetData } = useAppStore();
  const [isGenerating, setIsGenerating] = useState(false);
  const [selectedAlgo, setSelectedAlgo] = useState<"genetic" | "baseline">("genetic");

  const { restaurant, requirements, employees, schedule } = data;

  const metrics = schedule
    ? evaluateSchedule(restaurant, employees, requirements, schedule.assignments)
    : null;

  function handleGenerate() {
    setIsGenerating(true);
    setTimeout(() => {
      generateSchedule(selectedAlgo);
      setIsGenerating(false);
    }, 50);
  }

  return (
    <>
      <PageHeader
        title="Schedule"
        description="Staffing requirements derived from predictive covers, with automated roster assignments generated by optimization algorithms."
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              onClick={() => applyPredictedDemand()}
              title="Predict weekly guest covers and recalculate staffing needs"
            >
              <Brain className="h-4 w-4 mr-1 text-primary" />
              Forecast Demand (ML)
            </Button>
            <div className="flex rounded-md border border-input bg-background p-0.5 text-xs">
              <button
                type="button"
                className={`rounded px-2.5 py-1 font-medium transition-colors ${
                  selectedAlgo === "genetic"
                    ? "bg-primary text-primary-foreground"
                    : "text-muted-foreground hover:text-foreground"
                }`}
                onClick={() => setSelectedAlgo("genetic")}
              >
                Genetic AI
              </button>
              <button
                type="button"
                className={`rounded px-2.5 py-1 font-medium transition-colors ${
                  selectedAlgo === "baseline"
                    ? "bg-primary text-primary-foreground"
                    : "text-muted-foreground hover:text-foreground"
                }`}
                onClick={() => setSelectedAlgo("baseline")}
              >
                Baseline
              </button>
            </div>
            <Button size="sm" onClick={handleGenerate} disabled={isGenerating}>
              <Sparkles className="h-4 w-4 mr-1" />
              {isGenerating ? "Optimizing..." : "Generate schedule"}
            </Button>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => resetData()}
              title="Reset data to defaults"
            >
              <RotateCcw className="h-4 w-4" />
            </Button>
          </div>
        }
      />

      {metrics && (
        <div className="mb-6 grid grid-cols-2 gap-3 sm:grid-cols-4">
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Weekly Payroll</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {formatCurrency(metrics.totalLaborCost, restaurant.currency)}
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Coverage Rate</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {(metrics.coverageRate * 100).toFixed(1)}%
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Total Staff Hours</span>
            <p className="text-lg font-semibold tabular-nums text-foreground">
              {metrics.totalHours} hrs
            </p>
          </Card>
          <Card className="p-3">
            <span className="text-xs text-muted-foreground">Rule Breaches</span>
            <div className="flex items-center gap-1.5 mt-0.5">
              {metrics.violations.unqualified +
                metrics.violations.unavailable +
                metrics.violations.doubleBooked +
                metrics.violations.hoursOverMax ===
              0 ? (
                <>
                  <CheckCircle2 className="h-4 w-4 text-emerald-500" />
                  <span className="text-sm font-medium text-emerald-600">0 violations</span>
                </>
              ) : (
                <>
                  <AlertCircle className="h-4 w-4 text-amber-500" />
                  <span className="text-sm font-medium text-amber-600">
                    {metrics.violations.unqualified +
                      metrics.violations.unavailable +
                      metrics.violations.doubleBooked +
                      metrics.violations.hoursOverMax}{" "}
                    breaches
                  </span>
                </>
              )}
            </div>
          </Card>
        </div>
      )}

      <Card className="py-0">
        <div className="overflow-x-auto">
          <table className="w-full min-w-[880px] table-fixed text-sm">
            <thead className="border-b bg-muted/50 text-muted-foreground">
              <tr>
                <th scope="col" className="w-28 px-4 py-3 text-left font-medium">
                  <span className="sr-only">Service</span>
                </th>
                {DAYS_OF_WEEK.map((day) => (
                  <th key={day} scope="col" className="px-2 py-3 text-left font-medium">
                    {DAY_LABELS[day].short}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y">
              {SHIFT_PERIOD_IDS.map((periodId) => {
                const period = restaurant.shiftPeriods[periodId];
                return (
                  <tr key={periodId} className="align-top">
                    <th scope="row" className="px-4 py-4 text-left">
                      <span className="block font-medium">{period.label}</span>
                      <span className="text-xs font-normal text-muted-foreground tabular-nums">
                        {formatClock(period.startMinute)} - {formatClock(period.endMinute)}
                      </span>
                    </th>
                    {DAYS_OF_WEEK.map((day) => {
                      const reqs = requirements.filter(
                        (r) => r.day === day && r.periodId === periodId,
                      );
                      const totalNeeded = reqs.reduce((sum, r) => sum + r.count, 0);

                      const shiftAssignments = schedule
                        ? schedule.assignments.filter(
                            (a) => a.day === day && a.periodId === periodId,
                          )
                        : [];

                      return (
                        <td key={day} className="px-2 py-4">
                          {reqs.length === 0 ? (
                            <span className="text-xs text-muted-foreground">Closed</span>
                          ) : (
                            <div className="flex flex-col gap-1.5">
                              <div className="flex items-center justify-between text-xs text-muted-foreground">
                                <span className="tabular-nums font-medium">
                                  {schedule
                                    ? `${shiftAssignments.length}/${totalNeeded} filled`
                                    : `${totalNeeded} needed`}
                                </span>
                              </div>

                              {/* Assignments view if schedule generated */}
                              {schedule && shiftAssignments.length > 0 ? (
                                <div className="flex flex-col gap-1">
                                  {shiftAssignments.map((a, idx) => {
                                    const emp = employees.find((e) => e.id === a.employeeId);
                                    return (
                                      <div
                                        key={idx}
                                        className="flex items-center justify-between rounded bg-muted/60 px-1.5 py-0.5 text-xs"
                                      >
                                        <span className="truncate font-medium">
                                          {emp ? `${emp.firstName} ${emp.lastName[0]}.` : a.employeeId}
                                        </span>
                                        <Badge
                                          variant="outline"
                                          className="text-[10px] px-1 py-0 h-4 border-muted-foreground/30"
                                        >
                                          {ROLE_LABELS[a.role as Role]}
                                        </Badge>
                                      </div>
                                    );
                                  })}
                                </div>
                              ) : (
                                /* Role requirements summary badge */
                                reqs.map((r) => (
                                  <RoleBadge key={r.role} role={r.role} count={r.count} />
                                ))
                              )}
                            </div>
                          )}
                        </td>
                      );
                    })}
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </Card>
    </>
  );
}
